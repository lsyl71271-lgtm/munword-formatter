// Builds miniprogram/lib/munword-engine.js: the shared engine in app/ plus the
// stand-ins for browser globals in miniprogram-engine/runtime.js, as one
// CommonJS file the WeChat mini program can require().
//   node miniprogram-engine/build.mjs          write the bundle
//   node miniprogram-engine/build.mjs --check  fail if the committed bundle is stale
// It lives here, not in scripts/, and adds no dependency: scripts/, package.json and
// the lockfile are inputs of the offline build record (shared/local-build-policy.json).
import { build } from "esbuild";
import { readFile, writeFile } from "node:fs/promises";
import { createRequire } from "node:module";

export const OUTPUT = "miniprogram/lib/munword-engine.js";
// The mini program runtime runs no dynamic code. (References to Buffer, window or
// FileReader in pizzip and docxtemplater are all behind typeof checks; the
// sandbox test in tests/miniprogram.test.mjs runs the bundle without them.)
const FORBIDDEN = [/\bnew Function\s*\(/, /\beval\s*\(/, /\bimportScripts\s*\(/, /\brequire\s*\(\s*["'][^"']+["']\s*\)/];

// The XML parser is the @xmldom/xmldom that docxtemplater already depends on.
const XMLDOM = createRequire(createRequire(import.meta.url).resolve("docxtemplater")).resolve("@xmldom/xmldom");
const resolveXmldom = {
  name: "resolve-xmldom",
  setup(build) { build.onResolve({ filter: /^@xmldom\/xmldom$/ }, () => ({ path: XMLDOM })); },
};

// The engine's runtime-built patterns go through __miniRegExp (runtime.js), which
// is new RegExp() wherever lookbehind compiles; only the bundle sees the rename.
const routeRegExp = {
  name: "route-regexp",
  setup(build) {
    build.onLoad({ filter: /[\\/]app[\\/]docx-browser\.ts$/ }, async ({ path }) => {
      const code = await readFile(path, "utf8");
      const routed = code.replaceAll("new RegExp(", "__miniRegExp(");
      if (routed === code) throw new Error("app/docx-browser.ts has no new RegExp() left to route");
      return { contents: routed, loader: "ts" };
    });
  },
};

export async function bundle() {
  const result = await build({
    entryPoints: ["miniprogram-engine/entry.js"],
    bundle: true,
    write: false,
    format: "cjs",
    // "browser" so packages swap their Node-only files (pizzip's fs and streams) for browser ones.
    platform: "browser",
    target: "es2017",
    inject: ["miniprogram-engine/runtime.js"],
    plugins: [resolveXmldom, routeRegExp],
    minify: true,
    legalComments: "eof",
    charset: "utf8",
    logLevel: "silent",
  });
  const text = "/* Generated by miniprogram-engine/build.mjs from app/ and miniprogram-engine/. Do not edit. */\n" + result.outputFiles[0].text;
  const found = FORBIDDEN.filter(pattern => pattern.test(text));
  if (found.length) throw new Error(`Bundle uses what the mini program runtime lacks: ${found.join(", ")}`);
  return text;
}

/** runtime.js as an ES module for Node, for tests that use the stand-ins directly. */
export async function importRuntime() {
  const result = await build({ entryPoints: ["miniprogram-engine/runtime.js"], bundle: true, write: false, format: "esm", platform: "browser", target: "es2017", plugins: [resolveXmldom], logLevel: "silent" });
  return import(`data:text/javascript;base64,${Buffer.from(result.outputFiles[0].contents).toString("base64")}`);
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const text = await bundle();
  if (process.argv.includes("--check")) {
    const current = await readFile(OUTPUT, "utf8").catch(() => "");
    if (current !== text) { console.error(`${OUTPUT} is stale: run node miniprogram-engine/build.mjs`); process.exit(1); }
    console.log(`${OUTPUT} is up to date.`);
  } else {
    await writeFile(OUTPUT, text);
    console.log(`${OUTPUT}: ${(Buffer.byteLength(text) / 1024).toFixed(0)} KB`);
  }
}
